import { describe, it, expect, beforeAll } from 'vitest';
import app from '../../src/main.js';
import { prisma } from '../../src/prisma.js';
import { authed, ensureTestAuth } from '../request.js';
import { getDurableRunner } from '../../src/lib/jobs.js';
import { MemoryStore, setAttachmentStore, getAttachmentStore } from '../../src/ports/attachmentStore.js';
import { registerAttachmentJobs, MAX_ATTACHMENT_BYTES } from '../../src/services/attachmentService.js';
import { registerImportHandlers } from '../../src/import/service.js';

async function issue(key: string, summary = 'att') {
  // the beforeEach wipe deletes projects — each test re-creates what it needs
  const scheme = await prisma.permissionScheme.findFirstOrThrow({ where: { name: 'Default Permission Scheme' } });
  await prisma.project.upsert({ where: { key }, update: {}, create: { key, name: key, permissionSchemeId: scheme.id } });
  const res = await authed(app)
    .post('/rest/api/2/issue')
    .send({ fields: { project: { key }, summary } })
    .expect(201);
  return res.body.key as string;
}

const PNG = Buffer.from(
  'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==',
  'base64'
);

describe('Sprint 018 — attachments (slice 1: API + storage port)', () => {
  beforeAll(async () => {
    await ensureTestAuth();
    await (await import('../../src/seed.js')).seedPermissionDefaults();
    setAttachmentStore(new MemoryStore());
    registerAttachmentJobs();
    registerImportHandlers();
  });

  it('upload returns Jira-shaped metadata and fields.attachment[] updates', async () => {
    const key = await issue('ATT');

    const res = await authed(app)
      .post(`/rest/api/2/issue/${key}/attachments`)
      .set('X-Atlassian-Token', 'no-check')
      .attach('file', PNG, 'pic.png')
      .expect(200);
    expect(res.body).toHaveLength(1);
    const a = res.body[0];
    expect(a.filename).toBe('pic.png');
    expect(a.mimeType).toBe('image/png');
    expect(a.size).toBe(PNG.length);
    expect(a.author.displayName).toBe('Test Admin');
    expect(a.content).toContain(`/rest/api/2/attachment/content/${a.id}`);
    expect(a.self).toContain(`/rest/api/2/attachment/${a.id}`);

    const fetched = await authed(app).get(`/rest/api/2/issue/${key}`).expect(200);
    expect(fetched.body.fields.attachment).toHaveLength(1);
    expect(fetched.body.fields.attachment[0].filename).toBe('pic.png');
  });

  it('content download uses sniffed mime + safe headers; metadata + delete work', async () => {
    const key = await issue('ATT', 'download');
    const up = await authed(app)
      .post(`/rest/api/2/issue/${key}/attachments`)
      .attach('file', Buffer.from('plain text'), 'notes.txt')
      .expect(200);
    const id = up.body[0].id;

    await authed(app).get(`/rest/api/2/attachment/${id}`).expect(200);

    const content = await authed(app).get(`/rest/api/2/attachment/content/${id}`).expect(200);
    expect(content.headers['x-content-type-options']).toBe('nosniff');
    // text/plain is not inline-safe → forced download
    expect(content.headers['content-disposition']).toContain('attachment');
    expect(content.headers['content-security-policy']).toContain("default-src 'none'");

    await authed(app).delete(`/rest/api/2/attachment/${id}`).expect(204);
    await authed(app).get(`/rest/api/2/attachment/${id}`).expect(404);
    await authed(app).get(`/rest/api/2/attachment/content/${id}`).expect(404);
  });

  it('PNG serves inline; thumbnail is generated by the durable job', async () => {
    const key = await issue('ATT', 'thumb');
    const up = await authed(app)
      .post(`/rest/api/2/issue/${key}/attachments`)
      .attach('file', PNG, 'thumb.png')
      .expect(200);
    const id = up.body[0].id;

    const content = await authed(app).get(`/rest/api/2/attachment/content/${id}`).expect(200);
    expect(content.headers['content-disposition']).toContain('inline');
    expect(content.headers['content-type']).toBe('image/png');

    // thumbnail generated async by the durable job
    const runner = getDurableRunner();
    await (runner as { flush?: () => Promise<void> }).flush?.();
    const meta = await authed(app).get(`/rest/api/2/attachment/${id}`).expect(200);
    if (meta.body.thumbnail) {
      const thumb = await authed(app).get(`/rest/api/2/attachment/thumbnail/${id}`).expect(200);
      expect(thumb.headers['content-type']).toBe('image/png');
    }
    // sharp may be unavailable in CI — absence of a thumbnail is the documented fallback
  });

  it('corrupt image uploads fine and falls back (no thumbnail)', async () => {
    const key = await issue('ATT', 'corrupt');
    // .png extension but garbage bytes — sniffs to null, treated as octet-stream
    const up = await authed(app)
      .post(`/rest/api/2/issue/${key}/attachments`)
      .attach('file', Buffer.from('not really a png'), 'broken.png')
      .expect(200);
    const id = up.body[0].id;
    await (getDurableRunner() as { flush?: () => Promise<void> }).flush?.();
    // undecodable bytes → thumbnail job can't decode → no thumbnail (icon fallback)
    await authed(app).get(`/rest/api/2/attachment/thumbnail/${id}`).expect(404);
  });

  it('spoofed mime: claimed text/plain but sniffed png wins', async () => {
    const key = await issue('ATT', 'spoof');
    const up = await authed(app)
      .post(`/rest/api/2/issue/${key}/attachments`)
      .attach('file', PNG, { filename: 'evil.txt', contentType: 'text/plain' })
      .expect(200);
    expect(up.body[0].mimeType).toBe('image/png');
    const content = await authed(app).get(`/rest/api/2/attachment/content/${up.body[0].id}`).expect(200);
    expect(content.headers['content-type']).toBe('image/png');
    expect(content.headers['content-disposition']).toContain('inline');
  });

  it('SVG is never served inline — forced download + CSP', async () => {
    const key = await issue('ATT', 'svg');
    const svg = Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"><script>alert(1)</script></svg>');
    const up = await authed(app)
      .post(`/rest/api/2/issue/${key}/attachments`)
      .attach('file', svg, 'vec.svg')
      .expect(200);
    const content = await authed(app).get(`/rest/api/2/attachment/content/${up.body[0].id}`).expect(200);
    expect(content.headers['content-disposition']).toContain('attachment');
    expect(content.headers['content-security-policy']).toContain("default-src 'none'");
    expect(content.headers['content-type']).toBe('image/svg+xml');
  });

  it('limits are discoverable via /attachment/meta', async () => {
    const res = await authed(app).get('/rest/api/2/attachment/meta').expect(200);
    expect(res.body.enabled).toBe(true);
    expect(res.body.uploadLimit).toBe(MAX_ATTACHMENT_BYTES);
  });

  it('over-limit file returns 413 with the limit in the error', async () => {
    const key = await issue('ATT', 'big');
    const res = await authed(app)
      .post(`/rest/api/2/issue/${key}/attachments`)
      .attach('file', Buffer.alloc(MAX_ATTACHMENT_BYTES + 1), 'huge.bin');
    expect(res.status).toBe(413);
    expect(JSON.stringify(res.body)).toContain('25MB');
  });

  it('upload/delete write Attachment changelog items', async () => {
    const key = await issue('ATT', 'log');
    const up = await authed(app)
      .post(`/rest/api/2/issue/${key}/attachments`)
      .attach('file', Buffer.from('x'), 'log.txt')
      .expect(200);
    const id = up.body[0].id;
    await authed(app).delete(`/rest/api/2/attachment/${id}`).expect(204);

    const cl = await authed(app).get(`/rest/api/2/issue/${key}/changelog`).expect(200);
    const items = cl.body.histories.flatMap((h: { items: { field: string }[] }) => h.items);
    const att = items.filter((i: { field: string }) => i.field === 'Attachment');
    expect(att).toHaveLength(2); // add + remove (histories sort desc → delete first)
    expect(att[0].fromString).toBe('log.txt');
    expect(att[1].toString).toBe('log.txt');
  });

  it('visibility: no browse permission → 404 on all attachment routes', async () => {
    // a user with no grants on the project cannot see the attachment at all
    const key = await issue('ATT', 'hidden');
    const up = await authed(app)
      .post(`/rest/api/2/issue/${key}/attachments`)
      .attach('file', PNG, 'hidden.png')
      .expect(200);
    const id = up.body[0].id;

    // token scoped to a different project allow-list → 404 (existence hidden)
    const { plain, prefix, hash } = await import('../../src/lib/auth.js').then((m) => m.generateToken());
    const admin = await prisma.user.findFirstOrThrow({ where: { email: 'admin@test.local' } });
    await prisma.apiToken.create({
      data: { userId: admin.id, name: 'scoped', prefix, hash, scopes: ['read', 'write'], projectKeys: ['OTHER'] },
    });
    const request = (await import('supertest')).default;
    const server = app.listen(0);
    try {
      const scoped = request.agent(server).set('Authorization', `Bearer ${plain}`);
      await scoped.get(`/rest/api/2/attachment/${id}`).expect(404);
      await scoped.get(`/rest/api/2/attachment/content/${id}`).expect(404);
      await scoped.delete(`/rest/api/2/attachment/${id}`).expect(404);
      await scoped.post(`/rest/api/2/issue/${key}/attachments`).attach('file', PNG, 'x.png').expect(404);
    } finally {
      server.close();
    }
  });

  it('duplicate filenames are allowed; multi-file upload works', async () => {
    const key = await issue('ATT', 'dup');
    const res = await authed(app)
      .post(`/rest/api/2/issue/${key}/attachments`)
      .attach('file', Buffer.from('one'), 'same.txt')
      .attach('file', Buffer.from('two'), 'same.txt')
      .expect(200);
    expect(res.body).toHaveLength(2);
    expect(res.body[0].filename).toBe('same.txt');
    expect(res.body[1].filename).toBe('same.txt');
    const fetched = await authed(app).get(`/rest/api/2/issue/${key}`).expect(200);
    expect(fetched.body.fields.attachment).toHaveLength(2);
  });

  it('fixture import downloads bytes via the source and preserves author/created', async () => {
    const pngB64 = PNG.toString('base64');
    const fx = {
      '/rest/api/3/users/search': [],
      '/rest/api/3/project/ATTI': { id: '950', key: 'ATTI', name: 'AttImp' },
      '/rest/api/3/issuetype': [{ id: '1', name: 'Task' }],
      '/rest/api/3/status': [{ id: '10', name: 'To Do' }],
      '/rest/api/3/priority': [{ id: '3', name: 'Medium' }],
      '/rest/api/3/resolution': [],
      '/rest/api/3/role': [],
      '/rest/api/3/filter/search': { values: [] },
      '/rest/api/3/workflow/search': { values: [] },
      '/rest/api/3/field': [],
      '/rest/api/3/project/ATTI/components': [],
      '/rest/api/3/project/ATTI/versions': [],
      '/rest/api/3/search': {
        issues: [{
          id: '20001', key: 'ATTI-1',
          fields: {
            summary: 'i', issuetype: { name: 'Task' }, status: { name: 'To Do' },
            priority: { name: 'Medium' }, project: { key: 'ATTI' },
            attachment: [{
              id: 'att-1', filename: 'doc.png', size: PNG.length, mimeType: 'image/png',
              content: 'https://jira.example/secure/att/att-1/doc.png', created: '2024-01-02T03:04:05.000Z',
            }],
          },
        }],
        total: 1, startAt: 0, maxResults: 50,
      },
      'https://jira.example/secure/att/att-1/doc.png': { $binary: pngB64 },
    };
    const res = await authed(app)
      .post('/api/internal/migration/jira-cloud')
      .send({ projectKeys: ['ATTI'], fixture: fx })
      .expect(202);
    await (getDurableRunner() as { flush(): Promise<void> }).flush();
    const job = (await authed(app).get(`/api/internal/migration/${res.body.id}`).expect(200)).body;
    expect(job.stage).toBe('done');

    const issue = await prisma.issue.findFirstOrThrow({ where: { project: { key: 'ATTI' } }, include: { attachments: true } });
    expect(issue.attachments).toHaveLength(1);
    const a = issue.attachments[0];
    expect(a.filename).toBe('doc.png');
    expect(a.sniffedMime).toBe('image/png');
    expect(a.createdAt.toISOString()).toBe('2024-01-02T03:04:05.000Z');
    // bytes actually landed in the store
    const store = getAttachmentStore();
    expect((await store.get(a.storagePath)).equals(PNG)).toBe(true);
    // re-run is idempotent — no duplicates
    const res2 = await authed(app).post('/api/internal/migration/jira-cloud').send({ projectKeys: ['ATTI'], fixture: fx }).expect(202);
    await (getDurableRunner() as { flush(): Promise<void> }).flush();
    await authed(app).get(`/api/internal/migration/${res2.body.id}`).expect(200);
    expect(await prisma.attachment.count({ where: { issueId: issue.id } })).toBe(1);
  });

  it('issue delete purges stored bytes via the durable job', async () => {
    const key = await issue('ATT', 'purge');
    const up = await authed(app)
      .post(`/rest/api/2/issue/${key}/attachments`)
      .attach('file', Buffer.from('purgeme'), 'p.txt')
      .expect(200);
    const row = await prisma.attachment.findUniqueOrThrow({ where: { id: up.body[0].id } });
    const store = getAttachmentStore();
    expect((await store.get(row.storagePath)).length).toBeGreaterThan(0);

    // Jira delete flow: dry-run preview → confirmToken → delete
    const preview = await authed(app).delete(`/rest/api/2/issue/${key}?deleteSubtasks=true&dryRun=true`).expect(200);
    await authed(app)
      .delete(`/rest/api/2/issue/${key}?deleteSubtasks=true&confirmToken=${encodeURIComponent(preview.body.confirmToken)}`)
      .expect(204);
    await (getDurableRunner() as { flush?: () => Promise<void> }).flush?.();
    await expect(store.get(row.storagePath)).rejects.toThrow();
  });

  it('orphan sweep removes store files with no attachment row', async () => {
    const store = getAttachmentStore();
    await store.put('ghost/ghost/ghostid', Buffer.from('ghost'));
    await getDurableRunner().enqueue('attachment:sweep', {});
    await (getDurableRunner() as { flush?: () => Promise<void> }).flush?.();
    await expect(store.get('ghost/ghost/ghostid')).rejects.toThrow();
  });
});
